static const uint8_t *glyph(char c)
{
    unsigned v = (unsigned char)c;

    if (v >= 'a' && v <= 'z')
        v -= 32u;
    if (v < 0x20u || v > 0x5Fu)
        v = (unsigned)'?';
    return Font5x7[v - 0x20u];
}

void kshim_diag_fb_fill(uint32_t argb)
{
    for (unsigned y = 0; y < FB_H; ++y) {
        volatile uint32_t *line = (volatile uint32_t *)(uintptr_t)
            (FB_BASE + (unsigned long)y * FB_STRIDE);

        for (unsigned x = 0; x < FB_W; ++x)
            line[x] = argb;
    }
}

void kshim_diag_fb_clean(void)
{
    for (unsigned long off = 0; off < FB_BYTES; off += 64u)
        __asm__ volatile("dc cvac, %0" :: "r"(
            (uint64_t)(uintptr_t)(FB_BASE + off)) : "memory");
    __asm__ volatile("dsb sy" ::: "memory");
}

static void fb_pixel(unsigned x, unsigned y, uint32_t argb)
{
    if (x >= FB_W || y >= FB_H)
        return;
    ((volatile uint32_t *)(uintptr_t)(FB_BASE + (unsigned long)y * FB_STRIDE))[x] = argb;
}

unsigned kshim_diag_fb_puts(unsigned x, unsigned y, const char *s, uint32_t argb)
{
    const unsigned scale = KSHIM_DIAG_FB_SCALE;

    for (; s != NULL && *s != '\0'; ++s) {
        const uint8_t *g = glyph(*s);

        for (unsigned col = 0; col < 5u; ++col)
            for (unsigned row = 0; row < 7u; ++row)
                if ((g[col] & (1u << row)) != 0u)
                    for (unsigned dy = 0; dy < scale; ++dy)
                        for (unsigned dx = 0; dx < scale; ++dx)
                            fb_pixel(x + col * scale + dx, y + row * scale + dy, argb);
        x += 6u * scale;
    }
    return x;
}

unsigned kshim_diag_fb_hex(unsigned x, unsigned y, uint64_t v, unsigned digits,
                           uint32_t argb)
{
    static const char digits_txt[] = "0123456789ABCDEF";
    char buf[17];
    unsigned n = 0;

    if (digits == 0u || digits > 16u)
        digits = 16u;
    for (unsigned i = 0; i < digits; ++i) {
        unsigned nib = (unsigned)((v >> ((digits - 1u - i) * 4u)) & 0xFu);

        buf[i] = digits_txt[nib];
        n = i + 1u;
    }
    buf[n] = '\0';
    return kshim_diag_fb_puts(x, y, buf, argb);
}

unsigned kshim_diag_fb_dec(unsigned x, unsigned y, uint64_t v, uint32_t argb)
{
    char buf[21];
    unsigned n = 0;

    do {
        buf[n++] = (char)('0' + (unsigned)(v % 10u));
        v /= 10u;
    } while (v != 0u && n < sizeof buf - 1u);
    buf[n] = '\0';

    while (n > 0u)
        x = kshim_diag_fb_puts(x, y, (const char[]){buf[--n], '\0'}, argb);
    return x;
}