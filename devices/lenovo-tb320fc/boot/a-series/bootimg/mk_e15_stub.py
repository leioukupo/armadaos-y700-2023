#!/usr/bin/env python3
"""Generate the handover stub source (see e15_layout.py for the layout).

The stub runs where the kernel entry used to start, while the bootloader identity
map and caches are still live.  It paints the splash region green, lays red and
white calibration bars across it every 4 MB, writes the real address of the
appended pages into the DTB's kshim-append reservation so Linux cannot reuse that
memory, points x0 at our DTB, zeroes x1..x3, replays the displaced BL and resumes
at entry+4.  The last two words stay zero: build_e15.py fills them because they
branch to symbols the assembler does not know.

The bars probe the splash geometry.  The panel scans one frame inside the 45 MB
splash region, so the bars that show up say where that frame starts, how tall a
scanline really is and whether the panel is rotated.  The simplefb earlycon only
clears fb_stride*fb_height, so bars beyond that frame survive as a marker for
"the kernel never cleared the screen".
"""
import os
import sys

B = os.path.dirname(os.path.abspath(__file__))
WORK = os.path.join(B, 'e15')

sys.path.insert(0, B)
from e15_layout import layout  # noqa: E402

BAR_STEP = 0x400000			# one bar every 4 MB of the splash region
BAR_ROWS = 24				# scanlines tall, at the assumed stride
STRIDE = 6400				# the stride the DTB advertises
RED, WHITE, GREEN = 0x00FF0000, 0x00FFFFFF, 0x0000FF00

TEMPLATE = '''/* handover stub -- generated by mk_e15_stub.py, do not edit. */
	.text

	.globl	hook
hook:
	adr	x10, hook
	and	x10, x10, #-4096			/* x10 = appended pages base */

%(green)s
%(patch)s
%(bars)s
	mov	x0, x10
	add	x0, x0, #0x1000			/* x0 = our DTB, past the stub page */
	mov	x1, xzr
	mov	x2, xzr
	mov	x3, xzr

	.word	0				/* bl <displaced entry bl> */
	.word	0				/* b entry+4 */

/* paint: x11 = start, x12 = byte count, x13 = a8r8g8b8 colour */
paint:
	add	x15, x11, x12
	mov	x14, x11
1:	stp	x13, x13, [x14]
	add	x14, x14, #16
	cmp	x14, x15
	b.lo	1b
	mov	x14, x11
2:	dc	cvac, x14				/* clean to the point of coherence */
	add	x14, x14, #64
	cmp	x14, x15
	b.lo	2b
	dsb	sy
	isb
	ret
'''

PATCH = '''%(ph_addr)s
	add	x16, x10, x16			/* kshim-append reg cells */
	rev	w17, w10			/* the appended pages sit at x10, */
	str	w17, [x16, #4]			/* not at the image base */
	lsr	x18, x10, #32
	rev	w17, w18
	str	w17, [x16]
	dc	cvac, x16
	dsb	sy
	isb
'''


def mv(reg, val, indent='\t'):
    """movz/movk sequence for an arbitrary 64-bit constant."""
    val &= (1 << 64) - 1
    out = ['%smovz\t%s, #0x%x' % (indent, reg, val & 0xFFFF)]
    for i in (1, 2, 3):
        piece = (val >> (16 * i)) & 0xFFFF
        if piece:
            out.append('%smovk\t%s, #0x%x, lsl #%d' % (indent, reg, piece, 16 * i))
    return '\n'.join(out)


def paint(start, nbytes, colour):
    return '%s\n%s\n%s\n\tbl\tpaint\n' % (mv('x11', start), mv('x12', nbytes),
                                         mv('x13', colour))


def main():
    L = layout()
    green = paint(L['fb_base'], L['fb_bytes'], GREEN)

    bars = ''
    off, idx = 0, 0
    while off < L['fb_bytes']:
        span = min(BAR_ROWS * STRIDE, L['fb_bytes'] - off)
        bars += paint(L['fb_base'] + off, span, RED if idx % 2 == 0 else WHITE)
        off += BAR_STEP
        idx += 1

    asm = TEMPLATE % {
        'green': green.rstrip('\n'),
        'patch': (PATCH % {'ph_addr': mv('x16', L['stub_len'] + L['ph_off'])}).rstrip('\n'),
        'bars': bars.rstrip('\n'),
    }

    src = os.path.join(WORK, 'e15_stub.S')
    open(src, 'w', newline='\n').write(asm)
    print('wrote %s (%d bars, %d bytes of asm)' % (src, idx, len(asm)))
    print('layout: %s' % {k: hex(v) for k, v in L.items()})


if __name__ == '__main__':
    main()